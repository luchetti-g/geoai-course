import os, numpy as np, pandas as pd, geopandas as gpd, matplotlib.pyplot as plt
import rasterio
from affine import Affine
from rasterio.features import geometry_mask
import torch, torch.nn as nn, timm
from torch.utils.data import Dataset, DataLoader
from sklearn.metrics import f1_score, confusion_matrix, ConfusionMatrixDisplay

SAIDAS        = "/content/drive/MyDrive/Export-earth-engine/YOLO/saidas/"
TAM           = 96        # lado do recorte de cada copa, em pixels de 10 cm (9,6 m)
MASCARAR      = True      # zera o entorno da copa no recorte (reduz o aprendizado do fundo)
MIN_POR_CLASSE = 8        # morfotipos com menos copas típicas ficam de fora do treino
BLOCO         = 50        # lado dos blocos espaciais (m) para separar treino e teste
FRAC_TESTE    = 0.25      # fração dos blocos usada no teste
EPOCAS        = 25
LIMIAR_CONF   = 0.6       # abaixo disso a copa vira "indeterminada" no mapa
N_AL          = 20        # copas mostradas no active learning
USAR_CONVNEXT = False     # True = treina também uma ConvNeXt-Tiny para comparação
SEMENTE       = 42

np.random.seed(SEMENTE); torch.manual_seed(SEMENTE)
DISP = "cuda" if torch.cuda.is_available() else "cpu"
print("Processando em:", DISP)

"""## 2. Dados da Aula 9

Lê a pilha de bandas e as copas, mostra quantas copas típicas há em cada morfotipo e define as classes do treino.
"""

with rasterio.open(f"{SAIDAS}/recorte_pilha.tif") as s:
    P = s.read().astype("float32"); trp = s.transform; crs = s.crs
BANDAS = ["R", "G", "B", "RE", "NIR"]
C, Hh, Ww = P.shape
valido = ~np.isnan(P).any(0)
P = np.nan_to_num(P)

# imagem RGB para as figuras
def esticar(a):
    lo, hi = np.percentile(a[valido], (2, 98)); return np.clip((a - lo) / (hi - lo + 1e-9), 0, 1)
rgb_vis = np.dstack([esticar(P[i]) for i in range(3)])
ext = [trp.c, trp.c + trp.a * Ww, trp.f + trp.e * Hh, trp.f]

copas = gpd.read_file(f"{SAIDAS}/copas.gpkg").to_crs(crs).reset_index(drop=True)
copas["id_copa"] = copas.index
if "area_m2" not in copas: copas["area_m2"] = copas.geometry.area

tip = copas[copas.curadoria == "tipica"]
cont = tip.grupo.value_counts().sort_index()
CLASSES = [g for g in cont.index if cont[g] >= MIN_POR_CLASSE]
K = len(CLASSES)
idx_de = {g: i for i, g in enumerate(CLASSES)}
NOMES = [str(copas.loc[copas.grupo == g, "nome_grupo"].iloc[0]) for g in CLASSES]

display(pd.DataFrame({"morfotipo": [str(copas.loc[copas.grupo == g, "nome_grupo"].iloc[0]) for g in cont.index],
                      "copas típicas": cont.values,
                      "entra no treino": ["sim" if g in CLASSES else "não (poucas)" for g in cont.index]}, index=cont.index))
print(f"{K} classes no treino | {len(copas)} copas no total | {len(tip)} típicas")

"""## 3. Um recorte por copa

Cada copa vira um recorte de 96 × 96 pixels (9,6 m) centrado nela, com as 5 bandas **normalizadas banda a banda** (média 0, desvio 1).
Com `MASCARAR = True`, o que está fora da copa vira zero: o modelo é obrigado a olhar a copa, e não o capim ou a sombra em volta.
"""

MEDIA = np.array([P[i][valido].mean() for i in range(C)], "float32")
DESV  = np.array([P[i][valido].std() + 1e-6 for i in range(C)], "float32")
Pn = ((P - MEDIA[:, None, None]) / DESV[:, None, None]).astype("float32")
Pn[:, ~valido] = 0
meio = TAM // 2

def recorte(geom, A=Pn, mascarar=MASCARAR):
    col, lin = ~trp * (geom.centroid.x, geom.centroid.y)
    r0, c0 = int(lin) - meio, int(col) - meio
    out = np.zeros((A.shape[0], TAM, TAM), "float32")
    a0, b0 = max(r0, 0), max(c0, 0); a1, b1 = min(r0 + TAM, Hh), min(c0 + TAM, Ww)
    if a1 > a0 and b1 > b0:
        out[:, a0 - r0:a1 - r0, b0 - c0:b1 - c0] = A[:, a0:a1, b0:b1]
    if mascarar:
        m = geometry_mask([geom.buffer(0.3)], out_shape=(TAM, TAM), transform=trp * Affine.translation(c0, r0), invert=True)
        out[:, ~m] = 0
    return out

X_tip = np.stack([recorte(g) for g in tip.geometry])
y_tip = tip.grupo.map(idx_de).values
manter = ~pd.isna(y_tip)
X_tip, y_tip, tip_ok = X_tip[manter], y_tip[manter].astype(int), tip[manter]
print("Recortes de treino/teste:", X_tip.shape)

# exemplos: cor verdadeira e falsa-cor (NIR-R-G) de 4 copas por classe
fig, ax = plt.subplots(K, 8, figsize=(14, 1.9 * K), squeeze=False)
for k in range(K):
    sel = np.where(y_tip == k)[0][:4]
    for j, i in enumerate(sel):
        g = tip_ok.geometry.iloc[i]
        cru = recorte(g, A=P, mascarar=MASCARAR)
        v = lambda b: np.clip((cru[b] - np.percentile(P[b][valido], 2)) / (np.percentile(P[b][valido], 98) - np.percentile(P[b][valido], 2) + 1e-9), 0, 1)
        ax[k, 2 * j].imshow(np.dstack([v(0), v(1), v(2)])); ax[k, 2 * j + 1].imshow(np.dstack([v(4), v(0), v(1)]))
    for a in ax[k]: a.axis("off")
    ax[k, 0].set_title(NOMES[k], fontsize=8, loc="left")
plt.suptitle("O que a CNN recebe: cada par = cor verdadeira | falsa-cor"); plt.tight_layout(); plt.show()

"""## 4. Divisão espacial entre treino e teste

A área é dividida em blocos de 50 × 50 m. Blocos inteiros vão para o teste, para que o modelo seja avaliado em lugares que **não viu** no treino.
O sorteio é repetido até que todas as classes apareçam no treino e no teste.
"""

cen = tip_ok.centroid
bloco = ((cen.x - ext[0]) // BLOCO).astype(int) * 100 + ((cen.y - ext[2]) // BLOCO).astype(int)
blocos = np.array(sorted(bloco.unique()))
rng = np.random.default_rng(SEMENTE)
n_teste = max(1, round(FRAC_TESTE * len(blocos)))
ok = False
for _ in range(500):
    teste_b = set(rng.choice(blocos, n_teste, replace=False))
    em_teste = bloco.isin(teste_b).values
    if all((em_teste & (y_tip == k)).any() and (~em_teste & (y_tip == k)).any() for k in range(K)):
        ok = True; break
if not ok:
    print("ATENÇÃO: não foi possível ter todas as classes no treino e no teste. Aumente FRAC_TESTE ou diminua BLOCO.")

Xtr, ytr, Xte, yte = X_tip[~em_teste], y_tip[~em_teste], X_tip[em_teste], y_tip[em_teste]
print(f"Treino: {len(ytr)} copas | Teste: {len(yte)} copas")
display(pd.crosstab(pd.Series(np.array(NOMES)[y_tip], name="morfotipo"),
                    pd.Series(np.where(em_teste, "teste", "treino"), name="conjunto")))

fig, a = plt.subplots(figsize=(7, 7))
a.imshow(rgb_vis, extent=ext)
tip_ok[~em_teste].boundary.plot(ax=a, color="cyan", linewidth=1)
tip_ok[em_teste].boundary.plot(ax=a, color="orange", linewidth=1.5)
a.set_title("Copas de treino (azul) e de teste (laranja)"); a.axis("off"); plt.show()

"""## 5. Preparação do treino

- **Modelo:** EfficientNet-B0 pré-treinada na ImageNet (biblioteca `timm`). Com `in_chans=5`, a primeira camada é adaptada para 5 bandas, reaproveitando os pesos das bandas RGB.
- **Aumento de dados:** rotações de 90° e espelhamentos, sem mexer nas cores.
- **Perda ponderada:** classes com menos copas pesam mais, para o modelo não ignorar as raras.
"""

class Recortes(Dataset):
    def __init__(self, X, y, aumentar=False):
        self.X, self.y, self.aumentar = X, y, aumentar
    def __len__(self): return len(self.X)
    def __getitem__(self, i):
        x = self.X[i]
        if self.aumentar:
            x = np.rot90(x, np.random.randint(4), axes=(1, 2))
            if np.random.rand() < 0.5: x = x[:, :, ::-1]
        return torch.from_numpy(x.copy()), int(self.y[i])

def prever_probs(modelo, X, lote=64):
    modelo.eval(); saida = []
    with torch.no_grad():
        for i in range(0, len(X), lote):
            xb = torch.from_numpy(X[i:i + lote]).to(DISP)
            saida.append(torch.softmax(modelo(xb), 1).cpu().numpy())
    return np.concatenate(saida) if saida else np.zeros((0, K))

def treinar(canais, Xtr, ytr, arq="efficientnet_b0", epocas=EPOCAS, rotulo=""):
    modelo = timm.create_model(arq, pretrained=True, in_chans=len(canais), num_classes=K).to(DISP)
    freq = np.bincount(ytr, minlength=K)
    peso = 1 / np.sqrt(np.maximum(freq, 1)); peso = peso / peso.mean()
    perda = nn.CrossEntropyLoss(weight=torch.tensor(peso, dtype=torch.float32, device=DISP))
    otim = torch.optim.AdamW(modelo.parameters(), lr=3e-4, weight_decay=1e-4)
    dl = DataLoader(Recortes(Xtr[:, canais], ytr, True), batch_size=32, shuffle=True, drop_last=len(ytr) > 32)
    hist = []
    for ep in range(1, epocas + 1):
        modelo.train(); soma = 0
        for xb, yb in dl:
            xb, yb = xb.to(DISP), yb.to(DISP)
            loss = perda(modelo(xb), yb)
            otim.zero_grad(); loss.backward(); otim.step(); soma += loss.item() * len(xb)
        f1 = f1_score(yte, prever_probs(modelo, Xte[:, canais]).argmax(1), average="macro")
        hist.append((ep, soma / len(ytr), f1))
    h = pd.DataFrame(hist, columns=["época", "perda_treino", "F1_teste"])
    print(f"{rotulo}: F1 macro no teste = {h.F1_teste.iloc[-1]:.3f}")
    return modelo, h

CANAIS_RGB = [0, 1, 2]
CANAIS_MS  = [0, 1, 2, 3, 4]

"""## 6. Dois treinos: só RGB × RGB + red edge + NIR

Mesmo modelo, mesmas copas, mesma divisão; muda só a entrada. É o teste direto da pergunta: **o sensor multiespectral acrescenta informação útil?**
"""

modelo_rgb, h_rgb = treinar(CANAIS_RGB, Xtr, ytr, rotulo="Modelo A (RGB)")
modelo_ms,  h_ms  = treinar(CANAIS_MS,  Xtr, ytr, rotulo="Modelo B (RGB + RE + NIR)")
if USAR_CONVNEXT:
    modelo_cnx, h_cnx = treinar(CANAIS_MS, Xtr, ytr, arq="convnext_tiny", rotulo="ConvNeXt-Tiny (5 bandas)")

fig, ax = plt.subplots(1, 2, figsize=(13, 4))
for h, nome in [(h_rgb, "RGB"), (h_ms, "RGB + RE + NIR")] + ([(h_cnx, "ConvNeXt 5 bandas")] if USAR_CONVNEXT else []):
    ax[0].plot(h["época"], h.perda_treino, label=nome); ax[1].plot(h["época"], h.F1_teste, label=nome)
ax[0].set_title("Perda no treino"); ax[1].set_title("F1 macro no teste"); ax[1].set_ylim(0, 1)
for a in ax: a.set_xlabel("época"); a.legend()
plt.tight_layout(); plt.show()

"""**Para comentar:** a perda de treino cai sempre; o que importa é o F1 no teste. Se ele para de subir ou cai enquanto a perda continua caindo, o modelo está decorando o treino (sobreajuste).

> Aqui o conjunto de teste também é usado para acompanhar as épocas, por falta de copas para um conjunto de validação separado. Numa pesquisa, seriam três conjuntos: treino, validação e teste.

## 7. Avaliação no teste: matriz de confusão e F1 por morfotipo
"""

p_rgb = prever_probs(modelo_rgb, Xte[:, CANAIS_RGB]).argmax(1)
p_ms  = prever_probs(modelo_ms,  Xte[:, CANAIS_MS]).argmax(1)

fig, ax = plt.subplots(1, 2, figsize=(5 * 2 + K, 4 + 0.4 * K))
for a, pr, tit in [(ax[0], p_rgb, "Modelo A: RGB"), (ax[1], p_ms, "Modelo B: RGB + RE + NIR")]:
    ConfusionMatrixDisplay(confusion_matrix(yte, pr, labels=range(K)), display_labels=NOMES).plot(ax=a, colorbar=False, xticks_rotation=45)
    a.set_title(tit); a.set_xlabel("previsto"); a.set_ylabel("curadoria (referência)")
plt.tight_layout(); plt.show()

quadro = pd.DataFrame({
    "copas no teste": np.bincount(yte, minlength=K),
    "F1 RGB": f1_score(yte, p_rgb, labels=range(K), average=None, zero_division=0),
    "F1 RGB+RE+NIR": f1_score(yte, p_ms, labels=range(K), average=None, zero_division=0)}, index=NOMES)
quadro.loc["F1 macro"] = [len(yte), f1_score(yte, p_rgb, average="macro"), f1_score(yte, p_ms, average="macro")]
quadro["diferença"] = quadro["F1 RGB+RE+NIR"] - quadro["F1 RGB"]
quadro.round(2).to_csv(f"{SAIDAS}/quadro_RGB_x_multiespectral.csv")
display(quadro.round(2))

"""**Para comentar:**
- Quais morfotipos ficaram mais separáveis com o red edge e o NIR? Algum piorou?
- A diferença é grande o bastante para justificar uma câmera multiespectral?
- Com poucas copas no teste, uma ou duas copas mudam muito o F1: a comparação é indicativa, não definitiva.

## 8. Active learning: quais copas vale a pena rotular?

O modelo B prevê as copas **duvidosas** (fora do centro dos grupos) e mostramos as 20 em que ele está mais em dúvida: menor **margem** entre as duas classes mais prováveis.

**Antes da aula:** olhe a galeria e, para as copas em que você tem segurança, escreva o morfotipo correto em `ROTULOS_AL`, no formato `{id_copa: grupo}` (ex.: `{153: 2, 87: 0}`). Rode a célula seguinte: essas copas entram no treino e o modelo é refeito. Se deixar vazio, a seção só mostra as candidatas.
"""

duv = copas[copas.curadoria != "tipica"].copy()
X_duv = np.stack([recorte(g) for g in duv.geometry])
pr_duv = prever_probs(modelo_ms, X_duv[:, CANAIS_MS])
ordem = np.sort(pr_duv, 1)
duv["margem"] = ordem[:, -1] - ordem[:, -2]
duv["prev_1"] = [CLASSES[i] for i in pr_duv.argmax(1)]
duv["prev_2"] = [CLASSES[i] for i in np.argsort(pr_duv, 1)[:, -2]]
cand = duv.nsmallest(N_AL, "margem")

ncol = 5; nlin = int(np.ceil(len(cand) / ncol))
fig, ax = plt.subplots(nlin, ncol * 2, figsize=(ncol * 2 * 1.6, nlin * 1.9), squeeze=False)
for j, (_, r) in enumerate(cand.iterrows()):
    cru = recorte(r.geometry, A=P, mascarar=False)
    v = lambda b: np.clip((cru[b] - np.percentile(P[b][valido], 2)) / (np.percentile(P[b][valido], 98) - np.percentile(P[b][valido], 2) + 1e-9), 0, 1)
    l, c = divmod(j, ncol)
    ax[l, 2 * c].imshow(np.dstack([v(0), v(1), v(2)])); ax[l, 2 * c + 1].imshow(np.dstack([v(4), v(0), v(1)]))
    ax[l, 2 * c].set_title(f"id {r.id_copa}: g{r.prev_1} ou g{r.prev_2}\nmargem {r.margem:.2f}", fontsize=7, loc="left")
for a in ax.ravel(): a.axis("off")
plt.suptitle("Copas mais incertas para o modelo (cor verdadeira | falsa-cor)"); plt.tight_layout(); plt.show()
print("Grupos:", dict(zip(CLASSES, NOMES)))

ROTULOS_AL = {}          # {id_copa: grupo}; preencha após olhar a galeria

if ROTULOS_AL:
    novos = copas.loc[list(ROTULOS_AL)]
    X_novo = np.stack([recorte(g) for g in novos.geometry])
    y_novo = np.array([idx_de[ROTULOS_AL[i]] for i in novos.index])
    f1_antes = f1_score(yte, p_ms, average="macro")
    modelo_ms, h_ms = treinar(CANAIS_MS, np.concatenate([Xtr, X_novo]), np.concatenate([ytr, y_novo]),
                              rotulo=f"Modelo B + {len(y_novo)} copas do active learning")
    p_ms = prever_probs(modelo_ms, Xte[:, CANAIS_MS]).argmax(1)
    print(f"F1 macro antes: {f1_antes:.3f} | depois: {f1_score(yte, p_ms, average='macro'):.3f}")
else:
    print("ROTULOS_AL vazio: nenhuma copa nova; o modelo B segue como está.")

"""**Para comentar:** as copas difíceis têm algo em comum (sombra, borda, copas sobrepostas, um tipo de copa raro)? Rotular 20 copas escolhidas assim costuma ensinar mais ao modelo do que 20 copas sorteadas.

## 9. Mapa de morfotipos e contagem

O modelo B classifica **todas** as copas. Copas com confiança abaixo de `LIMIAR_CONF` ficam como **indeterminada**.
"""

X_todas = np.stack([recorte(g) for g in copas.geometry])
pr_todas = prever_probs(modelo_ms, X_todas[:, CANAIS_MS])
copas["classe_cnn"] = [CLASSES[i] for i in pr_todas.argmax(1)]
copas["confianca_cnn"] = pr_todas.max(1)
ord_t = np.sort(pr_todas, 1); copas["margem_cnn"] = ord_t[:, -1] - ord_t[:, -2]
nome_de = dict(zip(CLASSES, NOMES))
copas["morfotipo"] = np.where(copas.confianca_cnn >= LIMIAR_CONF, copas.classe_cnn.map(nome_de), "indeterminada")

fig, a = plt.subplots(figsize=(10, 10))
a.imshow(rgb_vis, extent=ext)
cl = copas[copas.morfotipo != "indeterminada"]
cl.plot(ax=a, column="morfotipo", cmap="tab10", categorical=True, alpha=0.55, edgecolor="black", linewidth=0.3, legend=True,
        legend_kwds={"loc": "upper left", "fontsize": 8})
copas[copas.morfotipo == "indeterminada"].boundary.plot(ax=a, color="white", linewidth=0.8, linestyle="--")
a.set_title("Mapa de morfotipos (branco tracejado = indeterminada)"); a.axis("off"); plt.show()

contagem = (copas.groupby("morfotipo").agg(copas=("id_copa", "count"), area_copa_m2=("area_m2", "sum"))
                 .sort_values("copas", ascending=False))
contagem["% das copas"] = (100 * contagem.copas / contagem.copas.sum()).round(1)
contagem.round(1).to_csv(f"{SAIDAS}/contagem_morfotipos.csv")
copas.to_file(f"{SAIDAS}/mapa_morfotipos.gpkg")
display(contagem.round(1))

"""## 10. Lista de copas para identificação em campo

Para cada morfotipo: as **5 copas típicas** de maior confiança (representam bem o grupo) e as **3 mais incertas** (podem esconder outra espécie). Com a identificação botânica dessas copas, os morfotipos podem ser renomeados, fundidos ou divididos.
"""

linhas = []
for g in CLASSES:
    d = copas[copas.classe_cnn == g]
    for tipo, sel in [("típica", d.nlargest(5, "confianca_cnn")), ("incerta", d.nsmallest(3, "margem_cnn"))]:
        s = sel.copy(); s["tipo_amostra"] = tipo; linhas.append(s)
campo = gpd.GeoDataFrame(pd.concat(linhas), crs=crs)
campo["geometry"] = campo.centroid
campo = campo.to_crs(4326)
